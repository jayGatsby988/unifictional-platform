import assert from 'node:assert/strict';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { defaultKitchen } from '../src/lib/spec/defaults';
import type { Project, EstimateSettings } from '../src/lib/spec/types';
import { calculateEstimate } from '../src/lib/estimate/estimator';
import { buildJarvisProposal } from '../src/lib/jarvis/proposal';
import { budgetFor, validateDesign } from '../src/lib/jarvis/validation';
import { designFingerprint, emptyJarvisState, type DesignOption } from '../src/lib/jarvis/types';
import { JarvisProposalView, jarvisProposalScope } from '../src/components/studio/JarvisProposalView';
import { fmtRange } from '../src/lib/units';

const now = '2026-09-10T00:00:00.000Z';
const settings: EstimateSettings = { region: 'seattle', tier: 'standard', contingencyPct: 0.1, markupPct: 0.2, scope: 'pull-and-replace', includePermits: true, mode: 'changes', includeKnockOns: true };
const source = defaultKitchen(), spec = structuredClone(source);
spec.island.present = false;
const selections = { ...source.materials, cabinets_base: 'wood-white-oak', countertop: 'ct-calacatta-quartz', island_cabinets: 'wood-walnut', island_countertop: 'ct-black-quartz' };
const snapshot = { spec, selections, estimateSettings: settings, baseline: { spec: source, selections: { ...source.materials }, capturedAt: now, source: 'demo' as const } };
const estimate = calculateEstimate(spec, selections, settings, snapshot.baseline);
const constraints = { budgetMax: 95000, keepAppliances: false, lockedSlots: [] };
assert.ok(estimate.totalHigh < constraints.budgetMax);
const option: DesignOption = { id: 'open-kitchen', name: 'Open kitchen', description: 'Exceeds budget at $85,000. The island has walnut cabinets and black quartz.', createdAt: now, snapshot, estimate, validation: validateDesign(snapshot, constraints), budget: budgetFor(estimate, constraints) };
const project: Project = { id: 'proposal-regression', name: 'Client kitchen', roomType: 'kitchen', createdAt: now, updatedAt: now, photos: [], description: '', ...snapshot, overrides: {}, scans: [], intake: null, jarvis: { ...emptyJarvisState(), constraints, options: [option] }, renders: [{ id: 'exact-render', provider: 'openai', status: 'completed', createdAt: now, selections, sourceUrl: 'https://example.com/actual-capture.png', sourceKind: 'viewport', resultUrl: 'https://example.com/exact-option-render.png', prompt: 'Saved option visualization', optionId: option.id, designFingerprint: designFingerprint(snapshot) }] };
const { proposal } = buildJarvisProposal({ project, optionIds: [option.id], title: 'Current options' });
const before = JSON.stringify(proposal);
const scope = jarvisProposalScope(proposal.options[0]);
assert.match(scope, /Island removed/);
assert.match(scope, /Base Cabinets: White Oak/);
assert.match(scope, /Countertop: Calacatta Gold Quartz/);
assert.doesNotMatch(scope, /Exceeds budget|85,000|Walnut|Absolute Black|Island cabinets|Island countertop/i);
assert.doesNotMatch(scope, /Flooring:/, 'unchanged active finishes do not become proposed changes');
const html = renderToStaticMarkup(createElement(JarvisProposalView, { proposal }));
assert.ok(!html.includes(option.description) && !html.includes('Exceeds budget') && !html.includes('Notes at creation'), 'archival AI prose is absent from the actual client proposal');
assert.equal((html.match(/Island removed/g) ?? []).length, 2, 'overview and option detail both use current scope');
assert.equal((html.match(/Open kitchen/g) ?? []).length >= 2, true, 'the saved option name remains');
assert.ok(html.includes('Full estimated range within budget'), 'current budget status remains authoritative');
const materialSection = html.split('Materials &amp; finishes</h3>')[1]?.split('<table')[0];
assert.ok(materialSection, 'actual material section is present');
assert.doesNotMatch(materialSection, /Island cabinets|Island countertop|Walnut|Absolute Black/i, 'absent island finishes are omitted from active materials');
const removed = proposal.options[0].estimate.lines.filter((line) => line.scope === 'removed');
assert.ok(removed.some((line) => line.id.includes('island')), 'real estimator retains removed-island scope');
assert.ok(html.includes('removed — demolition in allowance'), 'removed island demolition remains in priced scope');
assert.ok(html.includes(fmtRange(estimate.totalLow, estimate.totalHigh)), 'proposal displays unchanged real estimate range');
assert.ok(html.includes('https://example.com/exact-option-render.png'), 'the actual snapshot-bound render remains visible');
assert.equal(JSON.stringify(proposal), before, 'presentation does not alter immutable proposal or snapshots');

const unchanged: DesignOption = { ...option, snapshot: { ...snapshot, spec: source, selections: { ...source.materials } } };
assert.equal(jarvisProposalScope(unchanged), 'Existing layout and finishes retained.');
const noBaseline = { ...option, snapshot: { ...snapshot, baseline: null } };
assert.match(jarvisProposalScope(noBaseline), /Base Cabinets: White Oak/);
assert.doesNotMatch(jarvisProposalScope(noBaseline), /Island removed|Island cabinets|Island countertop/i, 'no baseline does not invent a removal or inactive finishes');

const underreported = structuredClone(project);
underreported.jarvis!.constraints.budgetMax = Math.floor(estimate.totalHigh - 1);
underreported.jarvis!.options[0].budget = { status: 'within', max: 95000, headroom: 90000 };
underreported.jarvis!.options[0].estimate.totalHigh = 1;
assert.throws(() => buildJarvisProposal({ project: underreported, optionIds: [option.id], title: 'Forged budget' }), /exceeds the current budget/, 'direct callers cannot bypass current budget with stale eligibility or forged totals');
const invalid = structuredClone(project);
const invalidSpec = invalid.jarvis!.options[0].snapshot.spec;
assert.equal(invalidSpec.roomType, 'kitchen');
if (invalidSpec.roomType === 'kitchen') {
  invalidSpec.island.present = true;
  invalidSpec.island.lengthFt = 14;
  invalidSpec.island.widthFt = 6;
}
invalid.jarvis!.options[0].validation = { valid: true, issues: [] };
assert.equal(validateDesign(invalid.jarvis!.options[0].snapshot, constraints).valid, false);
assert.throws(() => buildJarvisProposal({ project: invalid, optionIds: [option.id], title: 'Forged geometry' }), /Resolve the design errors/, 'direct callers cannot bypass actual geometry with stale validation');
assert.equal(JSON.stringify(proposal), before);
console.log('PASS rendered proposal current scope, stale prose exclusion, active materials, demolition, prices, render, immutability and server publication guards.');
