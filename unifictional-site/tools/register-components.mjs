// Regenerates lib/build/components/_ported.ts from the files in that folder.
//   node tools/register-components.mjs          # write _ported.ts
//   node tools/register-components.mjs --check  # only report
// Every <pack-id>.ts that is not one of the hand-registered originals (see
// index.ts) is imported and listed. Also reports duplicate `type` names and
// files that do not look like components.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, "..", "lib", "build", "components");
const check = process.argv.includes("--check");
const ORIGINALS = new Set(["menu-8", "scroll-41", "hero-type", "scroll-61", "scroll-47", "scroll-19", "scroll-15"]);
const SKIP = new Set(["_types", "_ported", "index", "generic"]);

const files = fs.readdirSync(dir).filter(f => f.endsWith(".ts")).map(f => f.slice(0, -3)).filter(f => !SKIP.has(f) && !ORIGINALS.has(f)).sort();
const types = new Map();
const problems = [];
const entries = [];
for (const f of files) {
  const src = fs.readFileSync(path.join(dir, f + ".ts"), "utf8");
  if (!/export default/.test(src)) { problems.push(`${f}.ts has no default export`); continue; }
  const id = (src.match(/\bid:\s*"([^"]+)"/) || [])[1];
  const type = (src.match(/\btype:\s*"([^"]+)"/) || [])[1];
  const kind = (src.match(/\bkind:\s*"([^"]+)"/) || [])[1];
  if (!id || !type || !kind) { problems.push(`${f}.ts is missing id/type/kind`); continue; }
  if (id !== f) problems.push(`${f}.ts declares id "${id}"`);
  if (!["menu", "transition", "cursor"].includes(type)) { if (types.has(type)) problems.push(`type "${type}" is used by ${types.get(type)} and ${f}`); else types.set(type, f); }
  entries.push({ f, ident: "c_" + f.replace(/[^a-z0-9]/gi, "_"), kind, type });
}
// generic.ts exports named components; include their types in the duplicate check
const generic = fs.readFileSync(path.join(dir, "generic.ts"), "utf8");
for (const m of generic.matchAll(/\btype:\s*"([^"]+)"/g)) if (types.has(m[1])) problems.push(`type "${m[1]}" collides with generic.ts (${types.get(m[1])})`);
for (const o of ORIGINALS) { const src = fs.readFileSync(path.join(dir, o + ".ts"), "utf8"); const t = (src.match(/\btype:\s*"([^"]+)"/) || [])[1]; if (t && types.has(t)) problems.push(`type "${t}" collides with ${o}.ts (${types.get(t)})`); }

const out = `// Generated by tools/register-components.mjs; do not edit by hand.
// Every pack component in this folder except the hand-registered originals in index.ts.
import type { Component } from "./_types";
${entries.map(e => `import ${e.ident} from "./${e.f}";`).join("\n")}

export const ported: Component[] = [
${entries.map(e => `  ${e.ident}, // ${e.kind} · ${e.type}`).join("\n")}
];
`;
console.log(`${entries.length} components (${Object.entries(entries.reduce((a, e) => (a[e.kind] = (a[e.kind] || 0) + 1, a), {})).map(([k, v]) => `${v} ${k}`).join(", ")})`);
if (problems.length) { console.log("PROBLEMS:"); for (const p of problems) console.log("  - " + p); }
if (!check) { fs.writeFileSync(path.join(dir, "_ported.ts"), out); console.log("wrote _ported.ts"); }
process.exit(problems.length && check ? 1 : 0);
